"""
seed_elo_from_irt.py
One-time script to seed question Elo ratings from calibrated IRT difficulties.

Formula:
    Elo = 1500 + 173.7178 × difficulty_logit

Where:
    - 1500 is the standard Elo anchor (matching student initial rating).
    - 173.7178 = 400 / ln(10), the canonical IRT-to-Elo scale conversion constant.

Outputs:
    - question_elo_seeds.json (portable seed dataset)
    - seed_questions_elo.sql (direct Supabase SQL migration script)
    - Updates Supabase `questions` table if credentials are provided in environment.
"""

import os
import json
import argparse
from pathlib import Path

# Mathematical conversion constants
ELO_CENTER = 1500.0
IRT_TO_ELO_FACTOR = 173.7178  # 400 / ln(10)


def irt_to_elo(logit: float) -> float:
    """Convert IRT difficulty logit to Elo rating."""
    return round(ELO_CENTER + IRT_TO_ELO_FACTOR * logit, 1)


def load_irt_difficulties(repo_root: Path) -> list[dict]:
    """Load question IRT difficulties from Layer 5 models or public data."""
    # Attempt 1: models/irt_params.json
    irt_json = repo_root / "layer5-analysis" / "models" / "irt_params.json"
    anonymized_q = repo_root / "layer5-analysis" / "data" / "anonymized" / "questions.csv"

    questions = []

    if anonymized_q.exists():
        import csv
        with open(anonymized_q, encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                questions.append(row)

    if irt_json.exists():
        with open(irt_json, encoding="utf-8") as f:
            params = json.load(f)
        item_params = params.get("item_params", [])
        seeds = []
        for i, q in enumerate(questions):
            if i < len(item_params):
                ip = item_params[i]
                diff = ip.get("difficulty", ip.get("b", 0.0))
                disc = ip.get("discrimination", ip.get("a", 1.0))
            else:
                diff = 0.0
                disc = 1.0

            elo = irt_to_elo(diff)
            seeds.append({
                "id": q["id"],
                "text": q.get("text", "")[:80] + "...",
                "topic": q.get("topic", "basics"),
                "difficulty_label": q.get("difficulty", "medium"),
                "difficulty_logit": round(diff, 4),
                "discrimination": round(disc, 4),
                "elo_rating": elo,
                "elo_games": 10,  # Prior calibration weight
            })
        return seeds

    # Fallback synthetic defaults based on difficulty labels
    seeds = []
    diff_mapping = {"easy": -0.75, "medium": 0.0, "hard": 0.75}
    for q in questions:
        lbl = q.get("difficulty", "medium").lower()
        logit = diff_mapping.get(lbl, 0.0)
        elo = irt_to_elo(logit)
        seeds.append({
            "id": q["id"],
            "text": q.get("text", "")[:80] + "...",
            "topic": q.get("topic", "basics"),
            "difficulty_label": lbl,
            "difficulty_logit": logit,
            "discrimination": 1.0,
            "elo_rating": elo,
            "elo_games": 10,
        })
    return seeds


def generate_sql_migration(seeds: list[dict], out_path: Path):
    """Generate SQL statements for Supabase to seed question Elo."""
    lines = [
        "-- Auto-generated by layer5-adaptive/seed_elo_from_irt.py",
        "-- Seeds question Elo ratings from calibrated IRT difficulties",
        "BEGIN;",
        "",
    ]
    for s in seeds:
        lines.append(
            f"UPDATE questions SET "
            f"elo_rating = {s['elo_rating']}, "
            f"elo_games = {s['elo_games']}, "
            f"difficulty_logit = {s['difficulty_logit']}, "
            f"discrimination = {s['discrimination']} "
            f"WHERE id = '{s['id']}';"
        )
    lines.append("")
    lines.append("COMMIT;")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"✅ Generated SQL migration: {out_path} ({len(seeds)} statements)")


def update_supabase_direct(seeds: list[dict]):
    """Update Supabase directly via python client if configured."""
    supabase_url = os.environ.get("SUPABASE_URL") or os.environ.get("NEXT_PUBLIC_SUPABASE_URL")
    supabase_key = os.environ.get("SUPABASE_SERVICE_ROLE_KEY")

    if not supabase_url or not supabase_key:
        print("Notice: SUPABASE_SERVICE_ROLE_KEY not set. Skipped direct DB update (use SQL file instead).")
        return

    try:
        from supabase import create_client
        client = create_client(supabase_url, supabase_key)
        print("Connecting to Supabase to update questions...")
        for s in seeds:
            client.table("questions").update({
                "elo_rating": s["elo_rating"],
                "elo_games": s["elo_games"],
                "difficulty_logit": s["difficulty_logit"],
                "discrimination": s["discrimination"],
            }).eq("id", s["id"]).execute()
        print(f"✅ Successfully updated {len(seeds)} questions in Supabase.")
    except Exception as e:
        print(f"Notice: Supabase direct update: {e}")


def main():
    parser = argparse.ArgumentParser(description="Seed question Elo ratings from IRT difficulties")
    parser.add_argument("--out-json", default="question_elo_seeds.json", help="Path to output JSON")
    parser.add_argument("--out-sql", default="seed_questions_elo.sql", help="Path to output SQL")
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent
    out_dir = Path(__file__).resolve().parent

    seeds = load_irt_difficulties(repo_root)
    print(f"Loaded {len(seeds)} questions with IRT parameters.")

    json_path = out_dir / args.out_json
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(seeds, f, indent=2)
    print(f"✅ Saved seed JSON: {json_path}")

    sql_path = out_dir / args.out_sql
    generate_sql_migration(seeds, sql_path)

    # Print summary of distribution
    elos = [s["elo_rating"] for s in seeds]
    if elos:
        print(f"\nElo Distribution Summary:")
        print(f"  Min Elo:    {min(elos):.1f}")
        print(f"  Mean Elo:   {sum(elos)/len(elos):.1f}")
        print(f"  Max Elo:    {max(elos):.1f}")

    update_supabase_direct(seeds)


if __name__ == "__main__":
    main()
