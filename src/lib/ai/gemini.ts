import { GENERATE_QUESTIONS_PROMPT, STUDENT_FEEDBACK_PROMPT } from './prompts';

const GEMINI_API_KEY = process.env.GEMINI_API_KEY || '';

interface GenerateQuestionsParams {
  topic: string;
  difficulty: 'easy' | 'medium' | 'hard';
  count: number;
}

export async function generateQuestionsWithGemini(params: GenerateQuestionsParams): Promise<any[]> {
  const prompt = GENERATE_QUESTIONS_PROMPT
    .replace('{topic}', params.topic)
    .replace('{difficulty}', params.difficulty)
    .replace('{count}', params.count.toString());

  if (!GEMINI_API_KEY) {
    // Curated high quality fallback when key is not configured
    return [
      {
        question_text: `In Git, when working on '${params.topic}', how do you view the commit divergence between your current branch and origin/main?`,
        option_a: "git status -v",
        option_b: "git log HEAD..origin/main --oneline",
        option_c: "git diff --dry-run",
        option_d: "git fetch --show-all",
        correct_answer: "b",
        explanation: "Using double-dot syntax with git log shows commits that are reachable from origin/main but not from your current HEAD.",
        topic_tag: params.topic.toLowerCase().replace(/\s+/g, '-'),
        difficulty: params.difficulty,
      },
      {
        question_text: `What is the recommended Git strategy to incorporate upstream changes into a feature branch without creating unnecessary merge commits?`,
        option_a: "git pull --rebase origin main",
        option_b: "git merge --strategy=ours origin/main",
        option_c: "git reset --hard origin/main",
        option_d: "git branch -m main",
        correct_answer: "a",
        explanation: "Rebasing during pull reapplies your feature branch commits cleanly on top of the latest upstream commits.",
        topic_tag: params.topic.toLowerCase().replace(/\s+/g, '-'),
        difficulty: params.difficulty,
      },
    ].slice(0, params.count);
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${GEMINI_API_KEY}`;

  const res = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 0.3,
        responseMimeType: 'application/json',
      },
    }),
  });

  if (!res.ok) {
    const errorText = await res.text();
    throw new Error(`Gemini API error (${res.status}): ${errorText}`);
  }

  const data = await res.json();
  const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!rawText) throw new Error('No content generated by Gemini');

  // Parse JSON
  const cleaned = rawText.replace(/```json/gi, '').replace(/```/g, '').trim();
  return JSON.parse(cleaned);
}

export async function generateStudentFeedbackWithGemini(context: {
  name: string;
  score: number;
  total_possible: number;
  rank: number;
  total_students: number;
  correct_count: number;
  total_questions: number;
  avg_time: number;
  topic_breakdown: string;
  weak_topics: string;
}): Promise<{ feedback: string; recommended_practice: string; performance_level: string }> {
  if (!GEMINI_API_KEY) {
    const accuracy = (context.correct_count / (context.total_questions || 1)) * 100;
    const level = accuracy > 75 ? 'advanced' : accuracy > 45 ? 'intermediate' : 'beginner';
    return {
      feedback: `Great effort, ${context.name}! You scored ${context.score} points and placed #${context.rank} out of ${context.total_students} participants. You demonstrated solid fundamentals in Git.`,
      recommended_practice: `Focus on practicing interactive rebasing and understanding the internal object model (trees, commits, blobs).`,
      performance_level: level,
    };
  }

  const prompt = STUDENT_FEEDBACK_PROMPT
    .replace('{name}', context.name)
    .replace('{score}', context.score.toString())
    .replace('{total_possible}', context.total_possible.toString())
    .replace('{rank}', context.rank.toString())
    .replace('{total_students}', context.total_students.toString())
    .replace('{correct_count}', context.correct_count.toString())
    .replace('{total_questions}', context.total_questions.toString())
    .replace('{avg_time}', context.avg_time.toString())
    .replace('{topic_breakdown}', context.topic_breakdown)
    .replace('{weak_topics}', context.weak_topics || 'None identified');

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${GEMINI_API_KEY}`;

  const res = await fetch(endpoint, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 0.4,
        responseMimeType: 'application/json',
      },
    }),
  });

  if (!res.ok) {
    throw new Error('Gemini API call failed');
  }

  const data = await res.json();
  const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  const cleaned = rawText.replace(/```json/gi, '').replace(/```/g, '').trim();
  return JSON.parse(cleaned);
}
